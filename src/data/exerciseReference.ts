export interface ExerciseDefinition {
  id: string;
  name: string;
  aliases: string[];           // Other names/abbreviations
  position: ExercisePosition;
  secondaryPosition?: ExercisePosition;  // For combo moves
  movementPattern: MovementPattern;
  secondaryPattern?: MovementPattern;    // For combo moves
  primaryMuscles: MuscleGroup[];         // Can have multiple primary targets
  secondaryMuscles: MuscleGroup[];
  gripDemand: 'high' | 'medium' | 'low' | 'none';
  isCompound: boolean;
  isPower: boolean;
  isFinisher: boolean;
  isWarmup: boolean;
  equipment: string[];
  description: string;
  cues: string[];              // Coaching cues
  status: 'verified' | 'needs_review' | 'unverified';

  // New tags for compound flow detection
  weightPath?: WeightPath;           // Where weight is at start/mid/end of movement
  movementPlane?: MovementPlane;     // Sagittal, frontal, or transverse
  equipmentOptions?: EquipmentOption[]; // Valid equipment configurations
}

